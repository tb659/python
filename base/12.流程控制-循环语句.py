""" 流程控制-循环语句 """

"""
while 循环 vs for 循环
    特性              while 循环                    for 循环
    核心逻辑           条件成立就循环                  遍历元素/固定次数就循环
    适用场景           不确定循环次数(按条件停止)        确定循环次数/遍历可迭代对象
    代码复杂度         需要手动更新条件(避免死循环)       无需手动控制，代码更简洁
    示例场景          等待用户输入“退出”后停止          遍历列表、计算1到n的和

控制关键字
    continue    跳过本次循环
    break       跳出本次循环

选择技巧:
    知道要执行几次，或要遍历列表/字符串:用for循环(简单高效)
    不知道循环次数，只知道停止条件:用while循环(比如等待用户操作)。
"""

# while计算 1+2+3+4+5+6

# 初始化总和为0
total = 0
# 初始化计数器为1
i = 1
# 当计数器小于等于6时继续循环
while i <= 6:
    # 将当前计数器的值加到总和上
    total += i
    # 计数器自增1
    i += 1
# 打印最终的总和
print(total)

# 使用range循环
# 初始化总和为0
total = 0
# 使用for循环遍历1到6的数字
for i in range(1, 7):
    # 将当前数字累加到总和中
    total += i
# 打印计算得到的总和
print(total)

print("根据 continue 跳过 写出对应的代码")
# 根据 continue 写出对应的代码
# 遍历1到9的数字
for i in range(1, 10):
    # 如果i是偶数，则跳过本次循环
    if i % 2 == 0:
        continue
    # 打印奇数
    print(i)

print("根据 break 跳出 写出对应的代码")
# 根据 break 写出对应的代码
# 遍历1到9的数字
for i in range(1, 10):
    # 如果i能被5整除，则跳出循环
    if i % 5 == 0:
        break
    # 打印不能被5整除的数字
    print(i)
