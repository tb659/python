""" 贪婪匹配&非贪婪匹配 """

"""
1.模式定义:
    贪婪模式(默认):量词尽可能多匹配，无需额外符号;。
    非贪婪模式:量词后加?，尽可能少匹配。
2.影响范围:只对量词(*、+、{m,n}、?)生效。
3.核心区别:
    贪婪:能多拿就多拿，直到无法继续;
    非贪婪:能少拿就少拿，满足最低要求即可。
4.实用技巧:
    提取"最近匹配""单个片段"用非贪婪(加?);。
    提取"完整片段""所有符合内容"用贪婪(默认);
    不确定时，两种模式都试一下，对比结果即可。

"""

import re

# 示例1: 量词 * (0次或多次)
# 规则: \d* → 匹配0个或多个数字，贪婪模式下尽可能多拿
res1 = re.match(r"\d*", "123456abc")
print("示例1贪婪匹配结果：", res1.group())  # 输出: 123456（拿完所有数字）

# 示例2: 量词 + (1次或多次)
# 规则: \d+ → 匹配1个或多个数字，贪婪模式下尽可能多拿
res2 = re.match(r"\d+", "123456abc")
print("示例2贪婪匹配结果：", res2.group())  # 输出: 123456（拿完所有数字）

# 示例3: 量词 {m,n} (m到n次)
# 规则: \d{2,5} → 匹配2-5个数字，贪婪模式下尽可能多拿（不超过5个）
res3 = re.match(r"\d{2,5}", "123456abc")
print("示例3贪婪匹配结果：", res3.group())  # 输出: 12345（拿满5个，不超过上限）

print("****************************************************************************")

html = "<div>第一部分</div><div>第二部分</div>"

# 贪婪模式: <div>.*</div> → 匹配从第一个<div>到最后一个</div>
res_greedy = re.search(r"<div>.*</div>", html)
print("贪婪模式提取HTML：", res_greedy.group())  # 输出: 整个字符串（过度匹配）

# 非贪婪模式: <div>.*?</div> → 匹配从第一个<div>到最近的</div>
res_non_greedy = re.search(r"<div>.*?</div>", html)
print("非贪婪模式提取HTML：", res_non_greedy.group())  # 输出: <div>第一部分</div>（只匹配一个）
